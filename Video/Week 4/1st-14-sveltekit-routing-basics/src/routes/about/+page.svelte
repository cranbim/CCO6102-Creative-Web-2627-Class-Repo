<h1>About</h1>

<p>
	This page lives at <code>src/routes/about/+page.svelte</code>. The folder name
	<code>about</code> becomes the URL path <code>/about</code> — that's the whole rule for
	simple routes. No configuration file, no route-registration step, nothing to import or
	wire up. Add a folder with a <code>+page.svelte</code> in it, and the route exists.
</p>

<p>
	Compare this to the Gallery pages — those go one level further, into a
	<strong>dynamic</strong> route.
</p>
