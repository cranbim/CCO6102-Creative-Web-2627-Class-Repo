<h1>About</h1>

<p>
	A page with no data at all. It lives at <code>src/routes/about/+page.svelte</code>, so its URL
	is <code>/about</code>.
</p>

<p>
	Compare it to the API route at <code>src/routes/api/ideas/+server.js</code>. Both are found by
	their <em>folder path</em>. The difference is the file name: <code>+page.svelte</code> makes a
	page (HTML for a person to look at), <code>+server.js</code> makes an endpoint (data for code
	to use).
</p>
